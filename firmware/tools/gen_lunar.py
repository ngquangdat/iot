#!/usr/bin/env python3
"""Generate src/GUI/lunar_data.c: Vietnamese lunar calendar table (UTC+7, Ho Ngoc Duc's algorithm).

One uint32 per lunar year Y (whose Tet falls in solar year Y):
  bits  0..12  month lengths in order (bit set = 30 days), leap month included after its normal month
  bits 13..16  leap month number (0 = none)
  bits 17..22  day of year of Tet (0 = Jan 1)
"""
import datetime, sys
from lunar import solar_to_lunar

FIRST, LAST = 2024, 2063

def tet(y):
    d = datetime.date(y, 1, 15)
    while solar_to_lunar(d.day, d.month, d.year)[:2] != (1, 1):
        d += datetime.timedelta(days=1)
    return d

def year_entry(y):
    start, end = tet(y), tet(y + 1)
    lengths, leap, d, cur = [], 0, start, None
    while d < end:
        ld, lm, ly, lp = solar_to_lunar(d.day, d.month, d.year)
        if ld == 1:
            if lp: leap = lm
            lengths.append(0)
        lengths[-1] += 1
        d += datetime.timedelta(days=1)
    assert len(lengths) in (12, 13) and all(n in (29, 30) for n in lengths), (y, lengths)
    assert (len(lengths) == 13) == (leap != 0)
    bits = sum(1 << i for i, n in enumerate(lengths) if n == 30)
    doy = (start - datetime.date(y, 1, 1)).days
    return bits | (leap << 13) | (doy << 17), start, leap

rows = [year_entry(y) for y in range(FIRST, LAST + 1)]
out = ["// Generated by tools/gen_lunar.py (Vietnamese lunar calendar, UTC+7). Do not edit.",
       '#include "lunar.h"', "",
       f"const uint16_t lunar_first_year = {FIRST};",
       f"const uint16_t lunar_year_count = {len(rows)};",
       "const uint32_t lunar_years[] = {"]
for y, (v, start, leap) in zip(range(FIRST, LAST + 1), rows):
    out.append(f"    0x{v:06X},  // {y}: Tet {start.isoformat()}" + (f", leap month {leap}" if leap else ""))
out.append("};")
open(sys.argv[1] if len(sys.argv) > 1 else "src/GUI/lunar_data.c", "w").write("\n".join(out) + "\n")
